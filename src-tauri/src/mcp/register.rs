//! Making the Splice MCP server visible to coding agents.
//!
//! Agents do not connect to Splice's HTTP endpoint directly. They launch a small
//! stdio shim (`splice_mcp.py`) that forwards each JSON-RPC line to the endpoint.
//! The shim is what makes the registration safe to leave in place:
//! - inside a Splice terminal it reads `SPLICE_ATTENTION_PORT` / `_TOKEN` /
//!   `SPLICE_TERMINAL_ID` from the environment, so the right instance is called and
//!   Splice knows which terminal is asking;
//! - elsewhere it falls back to the port and token files in the config dir;
//! - when Splice is not running, or the server is switched off, it answers the
//!   handshake itself with an empty tool list, so the agent starts normally.
//!
//! Registration goes through the agents' own CLIs (`claude mcp add-json`,
//! `codex mcp add`) rather than editing their config files, which they rewrite
//! while running.

use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

pub const SERVER_NAME: &str = "splice";
const SHIM_NAME: &str = "splice_mcp.py";
/// Bump when the shim or the registration command changes, to re-register once.
const REGISTRATION_VERSION: u32 = 2;
const CLI_TIMEOUT: Duration = Duration::from_secs(25);

const SHIM_TEMPLATE: &str = r#"#!/usr/bin/env python3
# splice-mcp-shim v1 (generated by Splice; do not edit, it is rewritten on launch)
"""stdio <-> HTTP bridge for the Splice MCP server.

Reads newline-delimited JSON-RPC from stdin, POSTs each message to the running
Splice instance, and writes the reply to stdout. If Splice cannot be reached or
its MCP server is off, answers the handshake locally with no tools.
"""
import json
import os
import sys
import urllib.request

CONFIG_DIR = __CONFIG_DIR__
OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def endpoint():
    port = os.environ.get('SPLICE_ATTENTION_PORT')
    token = os.environ.get('SPLICE_ATTENTION_TOKEN')
    if not (port and token):
        try:
            with open(os.path.join(CONFIG_DIR, '.attention_port')) as f:
                port = f.read().strip()
            with open(os.path.join(CONFIG_DIR, '.attention_token')) as f:
                token = f.read().strip()
        except OSError:
            return None
    if not (port and port.isdigit() and token):
        return None
    return 'http://127.0.0.1:%s/mcp' % port, token


def forward(line):
    target = endpoint()
    if target is None:
        return None
    url, token = target
    headers = {'Content-Type': 'application/json', 'X-Splice-Token': token}
    terminal_id = os.environ.get('SPLICE_TERMINAL_ID', '')
    if terminal_id.isdigit():
        headers['X-Splice-Terminal-Id'] = terminal_id
    req = urllib.request.Request(url, data=line.encode('utf-8'), headers=headers, method='POST')
    try:
        with OPENER.open(req, timeout=60) as resp:
            return resp.read().decode('utf-8')
    except Exception:
        return None


def offline(msg):
    """Reply when Splice is unreachable: a valid handshake and an empty tool list."""
    if not isinstance(msg, dict) or msg.get('id') is None or 'method' not in msg:
        return None
    method = msg['method']
    if method == 'initialize':
        version = (msg.get('params') or {}).get('protocolVersion') or '2025-06-18'
        result = {'protocolVersion': version, 'capabilities': {'tools': {}},
                  'serverInfo': {'name': 'splice', 'version': 'offline'}}
    elif method == 'tools/list':
        result = {'tools': []}
    elif method == 'ping':
        result = {}
    elif method == 'tools/call':
        result = {'content': [{'type': 'text', 'text': 'Splice is not running, or its MCP server is turned off in Settings.'}],
                  'isError': True}
    else:
        return {'jsonrpc': '2.0', 'id': msg['id'], 'error': {'code': -32601, 'message': 'Method not found'}}
    return {'jsonrpc': '2.0', 'id': msg['id'], 'result': result}


def main():
    for raw in sys.stdin:
        line = raw.strip()
        if not line:
            continue
        reply = forward(line)
        if reply is None:
            try:
                local = offline(json.loads(line))
            except ValueError:
                local = None
            reply = json.dumps(local) if local is not None else ''
        reply = reply.strip()
        if reply:
            sys.stdout.write(reply.replace('\n', ' ') + '\n')
            sys.stdout.flush()


if __name__ == '__main__':
    try:
        main()
    except (KeyboardInterrupt, BrokenPipeError):
        pass
"#;

/// The shim source with the config directory baked in.
pub fn shim_source(config_dir: &Path) -> String {
    let dir = serde_json::to_string(&config_dir.to_string_lossy()).unwrap_or_else(|_| "\"\"".into());
    SHIM_TEMPLATE.replace("__CONFIG_DIR__", &dir)
}

/// Where the shim lives: next to the token it reads.
pub fn shim_path(config_dir: &Path) -> PathBuf {
    config_dir.join("mcp").join(SHIM_NAME)
}

/// Write the shim if its content changed. Returns its path.
pub fn write_shim(config_dir: &Path) -> Result<PathBuf, String> {
    let path = shim_path(config_dir);
    let source = shim_source(config_dir);
    if std::fs::read_to_string(&path).ok().as_deref() != Some(source.as_str()) {
        super::write_private(&path, source.as_bytes())?;
    }
    Ok(path)
}

/// Outcome for one agent CLI.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
#[serde(tag = "state", content = "detail", rename_all = "snake_case")]
pub enum CliState {
    /// Nothing was attempted (server off, or a sandboxed test instance).
    #[default]
    None,
    Registered,
    /// The CLI is not installed (not on the login shell's PATH).
    NotFound,
    Failed(String),
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
pub struct Registration {
    #[serde(default)]
    pub version: u32,
    #[serde(default)]
    pub shim: String,
    #[serde(default)]
    pub claude: CliState,
    #[serde(default)]
    pub codex: CliState,
}

fn marker_path(config_dir: &Path) -> PathBuf {
    config_dir.join("mcp").join("registration.json")
}

pub fn load_registration(config_dir: &Path) -> Registration {
    std::fs::read_to_string(marker_path(config_dir))
        .ok()
        .and_then(|d| serde_json::from_str(&d).ok())
        .unwrap_or_default()
}

/// Single-quote a string for a POSIX-style shell (also valid in fish).
pub fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// The JSON handed to `claude mcp add-json`.
pub fn claude_server_json(shim: &Path) -> String {
    serde_json::json!({
        "type": "stdio",
        "command": "python3",
        "args": [shim.to_string_lossy()],
    })
    .to_string()
}

/// Run `script` in the user's login shell so their PATH (nvm, ~/.local/bin, …)
/// applies; a GUI-launched app has only the system PATH. Returns (ok, output).
fn run_in_login_shell(script: &str) -> Result<(bool, String), String> {
    let shell = std::env::var("SHELL").ok().filter(|s| !s.is_empty()).unwrap_or_else(|| "/bin/sh".into());
    let mut child = Command::new(&shell)
        .args(["-l", "-c", script])
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("could not start {shell}: {e}"))?;
    let started = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(_)) => break,
            Ok(None) if started.elapsed() > CLI_TIMEOUT => {
                let _ = child.kill();
                let _ = child.wait();
                return Err("timed out".into());
            }
            Ok(None) => std::thread::sleep(Duration::from_millis(50)),
            Err(e) => return Err(e.to_string()),
        }
    }
    let out = child.wait_with_output().map_err(|e| e.to_string())?;
    let mut text = String::from_utf8_lossy(&out.stdout).to_string();
    text.push_str(&String::from_utf8_lossy(&out.stderr));
    Ok((out.status.success(), text.trim().to_string()))
}

fn cli_exists(name: &str) -> bool {
    matches!(run_in_login_shell(&format!("command -v {name}")), Ok((true, _)))
}

fn last_line(s: &str) -> String {
    let line = s.lines().rev().find(|l| !l.trim().is_empty()).unwrap_or("").trim();
    super::inbox::truncate_bytes(line, 200).to_string()
}

fn register_claude(shim: &Path) -> CliState {
    if !cli_exists("claude") {
        return CliState::NotFound;
    }
    // Replace any earlier entry so a moved shim path is picked up.
    let _ = run_in_login_shell(&format!("claude mcp remove --scope user {SERVER_NAME}"));
    let cmd = format!("claude mcp add-json --scope user {SERVER_NAME} {}", sh_quote(&claude_server_json(shim)));
    match run_in_login_shell(&cmd) {
        Ok((true, _)) => CliState::Registered,
        Ok((false, out)) => CliState::Failed(last_line(&out)),
        Err(e) => CliState::Failed(e),
    }
}

fn register_codex(shim: &Path) -> CliState {
    if !cli_exists("codex") {
        return CliState::NotFound;
    }
    let _ = run_in_login_shell(&format!("codex mcp remove {SERVER_NAME}"));
    let cmd = format!("codex mcp add {SERVER_NAME} -- python3 {}", sh_quote(&shim.to_string_lossy()));
    match run_in_login_shell(&cmd) {
        Ok((true, _)) => match forward_env_through_codex() {
            Ok(()) => CliState::Registered,
            Err(e) => CliState::Failed(format!("registered, but Codex will not pass the terminal's identity to Splice: {e}")),
        },
        Ok((false, out)) => CliState::Failed(last_line(&out)),
        Err(e) => CliState::Failed(e),
    }
}

/// Codex starts an MCP server with a stripped environment: only variables named in
/// the server's `env_vars` come through from the terminal. Without them the shim
/// cannot tell which Splice instance or which terminal the agent runs in, and
/// `codex mcp add` has no flag for this, so the line is added to the table it wrote.
const CODEX_ENV_VARS: &str = r#"env_vars = ["SPLICE_ATTENTION_PORT", "SPLICE_ATTENTION_TOKEN", "SPLICE_TERMINAL_ID"]"#;

/// `config` with `env_vars` set in the `[mcp_servers.splice]` table; `None` when
/// it is already right. An error when the table is not there.
pub(crate) fn with_codex_env_vars(config: &str) -> Result<Option<String>, String> {
    let mut lines: Vec<&str> = config.lines().collect();
    let header = format!("[mcp_servers.{SERVER_NAME}]");
    let start = lines.iter().position(|l| l.trim() == header).ok_or("no splice entry in the Codex config")?;
    let end = lines[start + 1..].iter().position(|l| l.trim_start().starts_with('[')).map_or(lines.len(), |i| start + 1 + i);
    let existing = (start + 1..end).find(|&i| {
        let t = lines[i].trim_start();
        t.strip_prefix("env_vars").is_some_and(|rest| rest.trim_start().starts_with('='))
    });
    match existing {
        Some(i) if lines[i].trim() == CODEX_ENV_VARS => return Ok(None),
        Some(i) => lines[i] = CODEX_ENV_VARS,
        None => lines.insert(start + 1, CODEX_ENV_VARS),
    }
    Ok(Some(lines.join("\n") + "\n"))
}

fn forward_env_through_codex() -> Result<(), String> {
    let home = match std::env::var_os("CODEX_HOME").filter(|v| !v.is_empty()) {
        Some(dir) => PathBuf::from(dir),
        None => dirs::home_dir().ok_or("cannot find the home directory")?.join(".codex"),
    };
    let path = home.join("config.toml");
    let config = std::fs::read_to_string(&path).map_err(|e| e.to_string())?;
    let Some(updated) = with_codex_env_vars(&config)? else { return Ok(()) };
    let tmp = path.with_extension(format!("toml.tmp-{}", std::process::id()));
    std::fs::write(&tmp, updated).map_err(|e| e.to_string())?;
    std::fs::rename(&tmp, &path).map_err(|e| e.to_string())
}

/// Bring the agents' configuration in line with the setting. Blocking (spawns the
/// CLIs): call from a blocking thread. Idempotent and cheap when nothing changed:
/// a launch with the server already registered only compares a marker file.
pub fn sync(config_dir: &Path, enabled: bool, force: bool) -> Registration {
    let previous = load_registration(config_dir);
    if crate::state::config_dir_is_sandboxed() {
        // A test instance must not touch the user's agent configuration.
        if enabled {
            let _ = write_shim(config_dir);
        }
        return previous;
    }
    let marker = marker_path(config_dir);

    if !enabled {
        let was_registered = previous.claude == CliState::Registered || previous.codex == CliState::Registered;
        if was_registered || force {
            if previous.claude == CliState::Registered || force {
                let _ = run_in_login_shell(&format!("claude mcp remove --scope user {SERVER_NAME}"));
            }
            if previous.codex == CliState::Registered || force {
                let _ = run_in_login_shell(&format!("codex mcp remove {SERVER_NAME}"));
            }
        }
        let _ = std::fs::remove_file(&marker);
        return Registration::default();
    }

    let shim = match write_shim(config_dir) {
        Ok(p) => p,
        Err(e) => {
            return Registration { claude: CliState::Failed(e.clone()), codex: CliState::Failed(e), ..Default::default() };
        }
    };
    let shim_str = shim.to_string_lossy().to_string();
    let up_to_date = previous.version == REGISTRATION_VERSION
        && previous.shim == shim_str
        && !matches!(previous.claude, CliState::Failed(_) | CliState::None)
        && !matches!(previous.codex, CliState::Failed(_) | CliState::None);
    if up_to_date && !force {
        return previous;
    }

    let reg = Registration {
        version: REGISTRATION_VERSION,
        shim: shim_str,
        claude: register_claude(&shim),
        codex: register_codex(&shim),
    };
    if let Ok(data) = serde_json::to_string_pretty(&reg) {
        let _ = super::write_private(&marker, data.as_bytes());
    }
    reg
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shim_bakes_in_the_config_dir_as_a_python_string() {
        let src = shim_source(Path::new("/Users/x/Library/Application Support/Splice"));
        assert!(src.contains("CONFIG_DIR = \"/Users/x/Library/Application Support/Splice\""));
        assert!(!src.contains("__CONFIG_DIR__"));
        for needle in ["X-Splice-Token", "X-Splice-Terminal-Id", "SPLICE_ATTENTION_PORT", "ProxyHandler({})", "'tools': []"] {
            assert!(src.contains(needle), "shim lacks {needle}");
        }
    }

    #[test]
    fn codex_entry_gets_env_vars_once_and_other_tables_are_untouched() {
        let cfg = "model = \"x\"\n\n[mcp_servers.other]\ncommand = \"a\"\n\n[mcp_servers.splice]\ncommand = \"python3\"\nargs = [\"/s.py\"]\n\n[tui]\nk = 1\n";
        let out = with_codex_env_vars(cfg).unwrap().unwrap();
        assert!(out.contains(&format!("[mcp_servers.splice]\n{CODEX_ENV_VARS}\ncommand = \"python3\"")));
        assert_eq!(out.replace(&format!("{CODEX_ENV_VARS}\n"), ""), cfg);
        assert_eq!(with_codex_env_vars(&out).unwrap(), None);
        // A stale list is replaced; another server's list is not mistaken for ours.
        let stale = out.replace(CODEX_ENV_VARS, "env_vars = [\"OLD\"]").replace("command = \"a\"", "env_vars = [\"KEEP\"]");
        let fixed = with_codex_env_vars(&stale).unwrap().unwrap();
        assert!(fixed.contains(CODEX_ENV_VARS) && fixed.contains("env_vars = [\"KEEP\"]") && !fixed.contains("OLD"));
        assert!(with_codex_env_vars("[mcp_servers.other]\n").is_err());
    }

    #[test]
    fn write_shim_is_idempotent() {
        let d = tempfile::tempdir().unwrap();
        let p = write_shim(d.path()).unwrap();
        let first = std::fs::metadata(&p).unwrap().modified().unwrap();
        let again = write_shim(d.path()).unwrap();
        assert_eq!(p, again);
        assert_eq!(first, std::fs::metadata(&p).unwrap().modified().unwrap(), "unchanged content is not rewritten");
    }

    #[test]
    fn sh_quote_survives_single_quotes() {
        assert_eq!(sh_quote("a b"), "'a b'");
        assert_eq!(sh_quote("it's"), "'it'\\''s'");
    }

    #[test]
    fn claude_json_is_a_stdio_server_running_the_shim() {
        let v: serde_json::Value = serde_json::from_str(&claude_server_json(Path::new("/c/mcp/splice_mcp.py"))).unwrap();
        assert_eq!(v["type"], "stdio");
        assert_eq!(v["command"], "python3");
        assert_eq!(v["args"][0], "/c/mcp/splice_mcp.py");
    }

    #[test]
    fn registration_round_trips_and_defaults_to_none() {
        let d = tempfile::tempdir().unwrap();
        assert_eq!(load_registration(d.path()), Registration::default());
        let reg = Registration { version: 1, shim: "/x".into(), claude: CliState::Registered, codex: CliState::Failed("boom".into()) };
        std::fs::create_dir_all(d.path().join("mcp")).unwrap();
        std::fs::write(marker_path(d.path()), serde_json::to_string(&reg).unwrap()).unwrap();
        assert_eq!(load_registration(d.path()), reg);
    }

    /// The shim with nothing to talk to: a clean handshake and no tools, so an
    /// agent started while Splice is closed is not disturbed.
    #[test]
    fn shim_answers_the_handshake_offline_with_no_tools() {
        use std::io::Write;
        if Command::new("python3").arg("--version").output().is_err() {
            return;
        }
        let d = tempfile::tempdir().unwrap();
        let shim = write_shim(d.path()).unwrap();
        let mut child = Command::new("python3")
            .arg(&shim)
            .env_remove("SPLICE_ATTENTION_PORT")
            .env_remove("SPLICE_ATTENTION_TOKEN")
            .env_remove("SPLICE_TERMINAL_ID")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .spawn()
            .unwrap();
        child.stdin.take().unwrap().write_all(
            b"{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"initialize\",\"params\":{\"protocolVersion\":\"2025-06-18\"}}\n\
{\"jsonrpc\":\"2.0\",\"method\":\"notifications/initialized\"}\n\
{\"jsonrpc\":\"2.0\",\"id\":2,\"method\":\"tools/list\"}\n\
{\"jsonrpc\":\"2.0\",\"id\":3,\"method\":\"tools/call\",\"params\":{\"name\":\"spawn_agent\",\"arguments\":{}}}\n",
        ).unwrap();
        let out = child.wait_with_output().unwrap();
        let lines: Vec<serde_json::Value> = String::from_utf8_lossy(&out.stdout)
            .lines()
            .map(|l| serde_json::from_str(l).unwrap())
            .collect();
        assert_eq!(lines.len(), 3, "the notification gets no reply");
        assert_eq!(lines[0]["result"]["protocolVersion"], "2025-06-18");
        assert_eq!(lines[1]["result"]["tools"], serde_json::json!([]));
        assert_eq!(lines[2]["result"]["isError"], true);
    }
}
